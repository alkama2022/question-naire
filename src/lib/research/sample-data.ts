function expand(
  studyId: string,
  startCode: number,
  rows: Array<[string, "accepted" | "excluded" | "needs_review" | "pending" | "incomplete"]>,
): ResponseRecord[] {
  return rows.map(([day, kind], index) => ({
    id: `rsp-${studyId}-${index + 1}`,
    studyId,
    code: `RC-${startCode + index}`,
    createdAt: `${day}T08:30:00.000Z`,
    completedAt: kind === "incomplete" ? undefined : `${day}T10:15:00.000Z`,
    quality: kind === "incomplete" ? "pending" : kind,
    withdrawn: false,
    note: "",
    origin: "sample",
  }));
}

